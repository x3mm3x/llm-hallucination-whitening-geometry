def write_report(band_results, scan_results, eigenvalues, cumvar, output_dir):
    """Write comprehensive spectral decomposition report."""
    path = os.path.join(output_dir, 'induction_spectral_report.txt')
    lines = []

    lines.append("=" * 90)
    lines.append("SPECTRAL BAND DECOMPOSITION — EIGENSPECTRUM ANALYSIS OF HALLUCINATION SIGNATURES")
    lines.append("=" * 90)
    lines.append(f"\nModel: GPT-2-small (768D hidden states)")
    lines.append(f"PCA components: {len(eigenvalues)}")
    lines.append(f"Bands analyzed: {len(band_results)}")
    lines.append(f"Scan windows: {len(scan_results)}")

    # Eigenspectrum summary
    lines.append("\n" + "─" * 90)
    lines.append("EIGENSPECTRUM")
    lines.append("─" * 90)
    for n in [10, 50, 100, 256, 512]:
        if n <= len(cumvar):
            lines.append(f"  Top {n:>3} PCs: {cumvar[n-1]:.1%} variance")

    # Per-band results
    lines.append("\n" + "─" * 90)
    lines.append("PER-BAND RESULTS")
    lines.append("─" * 90)

    for br in band_results:
        lines.append(f"\n  {br['band_label']} (PCs {br['band_start']+1}–{br['band_end']+1}, "
                     f"{br['n_pcs']} dims, {br['variance_in_band']:.1%} of total variance)")
        lines.append(f"  {'─' * 70}")

        # 3-way tests
        for metric in ['H', 'max_sim', 'norm']:
            if metric in br['tests']:
                t = br['tests'][metric]
                sig = '***' if t['p'] < 0.001 else '**' if t['p'] < 0.01 else '*' if t['p'] < 0.05 else 'ns'
                lines.append(f"    KW {metric:>8}: H={t['H']:>8.2f}, p={t['p']:.2e} {sig}, "
                             f"ε²={t['eps2']:.4f}")

        # Pairwise — focus on Type 1 vs 2
        lines.append(f"    {'─' * 60}")
        for pair_suffix, pair_label in [('type1_vs_type2', 'T1 vs T2'),
                                        ('type1_vs_type3', 'T1 vs T3'),
                                        ('type2_vs_type3', 'T2 vs T3')]:
            for metric in ['H', 'max_sim', 'norm']:
                key = f"{metric}_{pair_suffix}"
                if key in br['pairwise']:
                    pw = br['pairwise'][key]
                    sig = '***' if pw['p'] < 0.001 else '**' if pw['p'] < 0.01 else '*' if pw['p'] < 0.05 else 'ns'
                    lines.append(f"    {pair_label} {metric:>8}: p={pw['p']:.2e} {sig}, "
                                 f"r={pw['r']:+.3f} "
                                 f"({pw['mean_1']:.4f} vs {pw['mean_2']:.4f})")

    # Type 1 vs Type 2: test spectral mixing hypothesis
    lines.append("\n" + "═" * 90)
    lines.append("SPECTRAL MIXING HYPOTHESIS: TYPE 1 vs TYPE 2 BY BAND")
    lines.append("═" * 90)
    lines.append("  (Prompt-level results are the primary inference level)")

    best_t1t2_p = 1.0
    best_t1t2_band = None
    best_t1t2_metric = None

    for br in band_results:
        for metric in ['H', 'max_sim', 'norm']:
            key = f"{metric}_type1_vs_type2"
            if key in br['pairwise']:
                p = br['pairwise'][key]['p']
                r = br['pairwise'][key]['r']
                sig = '***' if p < 0.001 else '**' if p < 0.01 else '*' if p < 0.05 else 'ns'
                label = f"{br['band_label']} / {metric}"
                lines.append(f"  {label:<40} p={p:.2e} {sig:>3}  r={r:+.3f}")
                if p < best_t1t2_p:
                    best_t1t2_p = p
                    best_t1t2_band = br['band_label']
                    best_t1t2_metric = metric

    lines.append(f"\n  Best T1 vs T2 result:")
    lines.append(f"    Band: {best_t1t2_band}")
    lines.append(f"    Metric: {best_t1t2_metric}")
    lines.append(f"    p = {best_t1t2_p:.2e}")
    if best_t1t2_p < 0.05:
        lines.append(f"    Prompt-level significant — spectral mixing hypothesis supported")
    else:
        lines.append(f"    Not significant — spectral mixing hypothesis rejected;")
        lines.append(f"    Type 1/2 non-separation is genuine (capacity hypothesis supported)")

    # Sliding scan summary
    if scan_results:
        lines.append("\n" + "─" * 90)
        lines.append("SLIDING WINDOW SCAN — TYPE 1 vs TYPE 2")
        lines.append("─" * 90)

        scan_best_p = 1.0
        scan_best_window = None
        for sr in scan_results:
            for metric in ['H', 'max_sim', 'norm']:
                key = f"{metric}_type1_vs_type2"
                if key in sr['pairwise']:
                    p = sr['pairwise'][key]['p']
                    if p < scan_best_p:
                        scan_best_p = p
                        scan_best_window = (sr['band_start'], sr['band_end'], metric)

        if scan_best_window:
            lines.append(f"  Best window: PCs {scan_best_window[0]+1}–{scan_best_window[1]+1} "
                         f"({scan_best_window[2]})")
            lines.append(f"  p = {scan_best_p:.2e}")
            if scan_best_p < 0.05:
                lines.append(f"  Significant at token level — verify at prompt level")
            else:
                lines.append(f"  Not significant — no spectral window resolves T1/T2")

            # Bonferroni correction
            n_tests = len(scan_results) * 3  # 3 metrics per window
            bonf_p = min(scan_best_p * n_tests, 1.0)
            lines.append(f"  Bonferroni-corrected (n={n_tests}): p = {bonf_p:.2e}")
            if bonf_p < 0.05:
                lines.append(f"  Survives Bonferroni correction")
            else:
                lines.append(f"  Does not survive Bonferroni correction")

    # Comparison across all four experiments (reference values from prior runs)
    lines.append("\n" + "═" * 90)
    lines.append("FOUR-EXPERIMENT PROGRESSION: TYPE 1 vs TYPE 2")
    lines.append("═" * 90)
    lines.append("  (Reference values from prior experiments; prompt-level p-values)")
    lines.append(f"  Static:             p ≈ 0.47     (Paper 2, Exp 1 — token-level H)")
    lines.append(f"  Raw contextual:     p ≈ 0.59     (Paper 2, Exp 2 — prompt-level H)")
    lines.append(f"  Whitened:           p ≈ 0.65     (Paper 3, Exp 1 — prompt-level H)")
    if best_t1t2_p < 1.0:
        lines.append(f"  Best spectral band: p = {best_t1t2_p:.2e}  (Paper 3, Exp 2 — this run)")
    lines.append(f"  Conclusion: Type 1/2 non-separation is consistent across all four experiments.")

    # Two-level survivor matrix (prompt-level, all bands × metrics × pairs)
    band_labels = [br['band_label'] for br in band_results]
    survivor_lines, survivors = format_survivors_summary(
        band_results, band_labels)
    lines.extend(survivor_lines)

    # Per-band two-level detail for survivors
    lines.append("\n" + "─" * 90)
    lines.append("TWO-LEVEL DETAIL FOR SURVIVING BANDS")
    lines.append("─" * 90)
    for br in band_results:
        band_lines = format_band_report(
            br['band_label'], br, ['H', 'norm', 'max_sim'])
        if len(band_lines) > 1:  # more than just the header
            lines.extend(band_lines)

    lines.append("\n" + "=" * 90)
    lines.append("END OF SPECTRAL DECOMPOSITION REPORT")
    lines.append("=" * 90)

    report = '\n'.join(lines)
    with open(path, 'w') as f:
        f.write(report)

    return report


