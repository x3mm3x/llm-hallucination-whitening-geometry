def compute_full_pca(calibration_hidden):
    """Compute full PCA on calibration data — we need all 768 components."""
    print("\n[Step 3] Computing full PCA decomposition...")
    t0 = time.time()

    mean = calibration_hidden.mean(axis=0)
    centered = calibration_hidden - mean

    # Full PCA — all components
    n_components = min(calibration_hidden.shape[0] - 1, calibration_hidden.shape[1])
    pca = PCA(n_components=n_components, random_state=CONFIG['random_seed'])
    pca.fit(centered)

    eigenvalues = pca.explained_variance_
    cumvar = np.cumsum(pca.explained_variance_ratio_)

    print(f"  Components computed: {n_components}")
    print(f"  Eigenvalue range: [{eigenvalues[-1]:.4f}, {eigenvalues[0]:.4f}]")
    print(f"  Top 10 PCs: {cumvar[9]:.1%} variance")
    print(f"  Top 50 PCs: {cumvar[49]:.1%} variance")
    print(f"  Top 100 PCs: {cumvar[99]:.1%} variance")
    print(f"  Top 256 PCs: {cumvar[255]:.1%} variance")
    print(f"  Done in {time.time() - t0:.1f}s")

    return mean, pca, eigenvalues, cumvar


def analyze_band(calibration_hidden, all_experimental, mean, pca, eigenvalues,
                 band_start, band_end, band_label, reg=1e-5):
    """Analyze a single spectral band with two-level testing.

    Projects all vectors onto PCs [band_start:band_end+1], whitens
    within that subspace, clusters, and computes geometric metrics.
    Preserves per-prompt structure for prompt-level testing.

    Returns dict with two-level test results + band metadata.
    """
    n_pcs = band_end - band_start + 1

    # Band projection matrix: select PCs and whiten
    components = pca.components_[band_start:band_end+1]  # (n_pcs, 768)
    band_eigenvalues = eigenvalues[band_start:band_end+1]
    scale = 1.0 / np.sqrt(band_eigenvalues + reg)

    # Whitening matrix for this band: project then scale
    W_band = components.T * scale  # (768, n_pcs)

    # Transform calibration
    centered_calib = calibration_hidden - mean
    whitened_calib = centered_calib @ W_band  # (n_calib, n_pcs)

    # Cluster in this band's whitened space
    n_clusters = min(CONFIG['n_clusters'], max(10, n_pcs // 2))
    kmeans = MiniBatchKMeans(
        n_clusters=n_clusters, random_state=CONFIG['random_seed'],
        batch_size=min(1024, whitened_calib.shape[0]),
        max_iter=300, n_init=5)
    kmeans.fit(whitened_calib)
    centroids = kmeans.cluster_centers_

    # Define compute function for this band (closure over W_band, centroids)
    def compute_band_metrics(hidden_states):
        centered = hidden_states - mean
        whitened = centered @ W_band
        sims = cosine_similarity(whitened, centroids)
        top_k = min(5, sims.shape[1])
        top_sims = np.sort(sims, axis=1)[:, -top_k:]
        return {
            'H': top_sims.mean(axis=1),
            'max_sim': sims.max(axis=1),
            'norm': np.linalg.norm(whitened, axis=1),
        }

    # Extract with per-prompt structure preserved
    prompt_data, token_data, diagnostics = extract_prompt_metrics_raw(
        all_experimental, compute_band_metrics)

    # Run two-level tests
    two_level = run_two_level_tests(
        prompt_data, token_data,
        metric_names=['H', 'max_sim', 'norm'],
        cfg={'n_permutations': 50000, 'n_bootstrap': 10000})

    # Add band metadata
    two_level['_meta'] = {
        'band_label': band_label.replace('\n', ' '),
        'band_start': band_start,
        'band_end': band_end,
        'n_pcs': n_pcs,
        'n_clusters': n_clusters,
        'variance_in_band': float(
            pca.explained_variance_ratio_[band_start:band_end+1].sum()),
    }

    # Also keep legacy token-level results for backward compat with figures
    two_level['_legacy'] = {
        'tests': {}, 'pairwise': {}, 'means': {},
    }
    types = sorted(token_data.keys())
    for metric_name in ['H', 'max_sim', 'norm']:
        groups = [token_data[t][metric_name] for t in types]
        if all(len(g) > 0 for g in groups):
            H_stat, p_val = stats.kruskal(*groups)
            N = sum(len(g) for g in groups)
            eps2 = (H_stat - len(groups) + 1) / (N - len(groups)) if N > len(groups) else 0
            two_level['_legacy']['tests'][metric_name] = {
                'H': float(H_stat), 'p': float(p_val), 'eps2': float(eps2)
            }
        for i, t1 in enumerate(types):
            for t2 in types[i+1:]:
                g1, g2 = token_data[t1][metric_name], token_data[t2][metric_name]
                if len(g1) > 0 and len(g2) > 0:
                    U, p = stats.mannwhitneyu(g1, g2, alternative='two-sided')
                    n1, n2 = len(g1), len(g2)
                    r = 1 - (2 * U) / (n1 * n2)
                    two_level['_legacy']['pairwise'][f"{metric_name}_{t1}_vs_{t2}"] = {
                        'U': float(U), 'p': float(p), 'r': float(r),
                        'mean_1': float(g1.mean()), 'mean_2': float(g2.mean()),
                    }
    for ctype in types:
        two_level['_legacy']['means'][ctype] = {}
        for metric_name in ['H', 'max_sim', 'norm']:
            arr = token_data[ctype][metric_name]
            two_level['_legacy']['means'][ctype][metric_name] = {
                'mean': float(arr.mean()), 'std': float(arr.std()),
            }

    return two_level


def run_sliding_scan(calibration_hidden, all_experimental, mean, pca,
                     eigenvalues, width, step, max_pc):
    """Sliding window scan across the eigenspectrum."""
    print(f"\n[Step 5b] Sliding window scan (width={width}, step={step})...")
    t0 = time.time()

    max_available = len(eigenvalues)
    scan_limit = min(max_pc, max_available)
    scan_results = []

    starts = list(range(0, scan_limit - width + 1, step))
    for i, start in enumerate(starts):
        end = start + width - 1
        r = analyze_band(calibration_hidden, all_experimental, mean, pca,
                         eigenvalues, start, end, f"PC {start+1}–{end+1}")
        scan_results.append(r)
        if (i + 1) % 5 == 0 or i == len(starts) - 1:
            print(f"    Scan: {i+1}/{len(starts)} windows")

    print(f"  Scan complete in {time.time() - t0:.1f}s")
    return scan_results


def add_legacy_compat(br):
    """Add old-format keys to a two-level band result for figure/report compat.

    The figures and parts of write_report access br['pairwise'], br['tests'],
    br['band_label'] etc. This function maps those from the new two-level
    structure's _legacy and _meta fields.
    """
    meta = br.get('_meta', {})
    legacy = br.get('_legacy', {})
    br['band_label'] = meta.get('band_label', '')
    br['band_start'] = meta.get('band_start', 0)
    br['band_end'] = meta.get('band_end', 0)
    br['n_pcs'] = meta.get('n_pcs', 0)
    br['n_clusters'] = meta.get('n_clusters', 0)
    br['variance_in_band'] = meta.get('variance_in_band', 0)
    br['tests'] = legacy.get('tests', {})
    br['pairwise'] = legacy.get('pairwise', {})
    br['means'] = legacy.get('means', {})
    return br


