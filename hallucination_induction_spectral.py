#!/usr/bin/env python3
"""
Geometric Hallucination Taxonomy — Spectral Band Decomposition
=================================================================

Decomposes contextual hidden states into eigenspectrum bands and tests
each band separately for hallucination-type separation. Tests two
competing hypotheses for the Type 1/2 non-separation found in Paper 2:

  Spectral mixing hypothesis: The Type 1/2 signal exists but is
    concentrated in specific eigenspectrum bands, diluted when
    full-dimensional metrics aggregate across all components.
  Capacity hypothesis: The Type 1/2 signal does not exist at 124M
    parameters — the model lacks representational precision for this
    distinction.

Result: The spectral mixing hypothesis is rejected. Type 1/2 does not
survive prompt-level aggregation in any spectral band (best p = 0.082).
The Type 3 signal is spectrally structured: angular metrics in mid-range
components, magnitude in the tail, dead zone at PCs 17-48.

Architecture:
  1. Generate calibration + experimental hidden states (same as whitened)
  2. Compute full PCA on calibration (768 components)
  3. Define spectral bands across the eigenspectrum
  4. For each band: project → whiten → cluster → measure → test
  5. Sliding window scan across eigenspectrum
  6. Two-level analysis: prompt-level (N=15, primary) + token-level (reference)

NOTE: Publication figures for Paper 3 are generated by generate_figures.py
from the summary_spectral.json output, not by this script's internal
figure generation. The figures below are diagnostic/exploratory.

Outputs (in ./results_induction_spectral/):
  - induction_spectral_report.txt     : full results with per-band tests
  - fig_spectral_bands.png            : KW p-values per band (all pairs)
  - fig_spectral_scan.png             : sliding window scan
  - fig_eigenspectrum.png             : eigenvalue distribution + variance
  - summary_spectral.json             : machine-readable results

Hardware: CPU only, ~4–8GB RAM, ~25–40 min runtime
Usage:  python hallucination_induction_spectral.py
"""

