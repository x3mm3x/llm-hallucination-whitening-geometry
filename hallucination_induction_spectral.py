def main():
    print("=" * 70)
    print("SPECTRAL BAND DECOMPOSITION — EIGENSPECTRUM ANALYSIS")
    print("=" * 70)
    t_start = time.time()

    os.makedirs(CONFIG['output_dir'], exist_ok=True)

    # Step 1: Load model
    model, tokenizer, static_emb = load_gpt2()

    # Step 2: Build calibration distribution
    calibration_hidden = build_calibration(model, tokenizer)

    # Step 3: Full PCA
    mean, pca, eigenvalues, cumvar = compute_full_pca(calibration_hidden)

    # Step 4: Generate experimental sequences (capture raw hidden states)
    print("\n[Step 4] Generating experimental sequences...")
    all_experimental = []
    for prompts, label in [(TYPE1_PROMPTS, 'type1'),
                           (TYPE2_PROMPTS, 'type2'),
                           (TYPE3_PROMPTS, 'type3')]:
        results = generate_experimental(model, tokenizer, prompts, label)
        all_experimental.extend(results)

    # Free model memory — we only need the hidden states from here
    del model
    gc.collect()

    # Step 5a: Analyze fixed bands
    print("\n[Step 5a] Analyzing spectral bands...")
    t0 = time.time()
    band_results = []
    max_available = len(eigenvalues)
    for start, end, label in CONFIG['bands']:
        if start >= max_available:
            print(f"    Skipping {label} — only {max_available} PCs available")
            continue
        end = min(end, max_available - 1)
        print(f"    Analyzing {label} (PCs {start+1}–{end+1})...")
        r = analyze_band(calibration_hidden, all_experimental, mean, pca,
                         eigenvalues, start, end, label)
        add_legacy_compat(r)
        band_results.append(r)
    print(f"  Band analysis done in {time.time() - t0:.1f}s")

    # Step 5b: Sliding window scan
    scan_results = run_sliding_scan(
        calibration_hidden, all_experimental, mean, pca, eigenvalues,
        CONFIG['scan_width'], CONFIG['scan_step'], CONFIG['scan_max_pc'])
    for sr in scan_results:
        add_legacy_compat(sr)

    # Step 6: Figures (diagnostic — publication figures from generate_figures.py)
    if CONFIG['generate_figures']:
        print("\n[Step 6] Generating diagnostic figures...")
        generate_figures(band_results, scan_results, eigenvalues, cumvar,
                         CONFIG['output_dir'])
    else:
        print("\n[Step 6] Skipping figures (generate_figures=False)")

    # Step 7: Report
    report = write_report(band_results, scan_results, eigenvalues, cumvar,
                          CONFIG['output_dir'])

    # Step 8: Save machine-readable results
    summary = {
        'band_results': [{
            '_meta': br.get('_meta', {}),
            'two_level': results_to_json({k: v for k, v in br.items()
                                          if not k.startswith('_') and k not in
                                          ('band_label', 'band_start', 'band_end',
                                           'n_pcs', 'n_clusters', 'variance_in_band',
                                           'tests', 'pairwise', 'means')}),
            'legacy_pairwise': br.get('pairwise', {}),
        } for br in band_results],
        'scan_summary': [{
            'band_start': sr.get('band_start', sr.get('_meta', {}).get('band_start', 0)),
            'band_end': sr.get('band_end', sr.get('_meta', {}).get('band_end', 0)),
            'tests': sr.get('tests', {}),
            'pairwise': sr.get('pairwise', {}),
        } for sr in scan_results],
        'eigenvalues': eigenvalues[:100].tolist(),
        'cumvar_checkpoints': {
            str(n): float(cumvar[n-1]) for n in [10, 50, 100, 256, 512]
            if n <= len(cumvar)
        },
    }
    with open(os.path.join(CONFIG['output_dir'], 'summary_spectral.json'), 'w') as f:
        json.dump(summary, f, indent=2, default=str)

    print(f"\n{'=' * 70}")
    print(f"COMPLETE — Total runtime: {time.time() - t_start:.1f}s")
    print(f"Results in: {os.path.abspath(CONFIG['output_dir'])}")
    print(f"{'=' * 70}")
    print("\n" + report)


if __name__ == '__main__':
    main()
